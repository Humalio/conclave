/**
 * The route scope registry (docs/multi-user.md §2): every /api route declares who may call it. The admin auth hook looks
 * each request up by its route pattern and refuses anything undeclared (fail closed), so a new route is admin-only until
 * someone scopes it here; test/multiuser-mu1.test.ts fails while a registered route is missing.
 *
 *   public   - no session (sign-in)
 *   self     - the signed-in user's own data
 *   admin    - admins only; members get 403 admin_only
 *   filtered - granted projects only, by component
 *   decider  - items routed to the user
 *
 * Members reach public and self routes (MEMBER_LIVE), and the filtered and decider routes whose handlers filter or
 * route for them (MEMBER_READY). Every other filtered or decider route answers them 403 admin_only, so a route whose
 * handler does not filter yet leaks nothing.
 */
